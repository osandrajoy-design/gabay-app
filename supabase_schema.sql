-- GABAY / Supabase PostgreSQL schema
-- Run this in Supabase Dashboard -> SQL Editor.
-- This replaces SQLite tables. Do NOT run the old SQLite CREATE TABLE statements.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email text unique not null,
  password text not null,
  role text not null default 'citizen',
  profile_image text
);

create table if not exists public.app_settings (
  key text primary key,
  value text,
  updated_at text
);

create table if not exists public.requests (
  id bigint generated by default as identity primary key,
  ticket_number text unique not null,
  user_id bigint not null references public.users(id),
  category text not null,
  description text not null,
  contact_number text not null,
  email text,
  address text not null,
  latitude text,
  longitude text,
  priority text not null default 'Analyzing',
  status text not null default 'Pending',
  assigned_department text,
  verification_image text,
  created_at text not null,
  updated_at text,
  analysis_status text default 'completed',
  forwarded integer default 0,
  forward_method text,
  forward_target text,
  forwarded_by bigint,
  forwarded_at text,
  assigned_to bigint,
  ai_report text,
  map_screenshot text,
  report_attachment text,
  report_submitted_at text,
  population_affected integer,
  households_affected integer,
  urgency text,
  outage_type text,
  outage_started_at text,
  report_title text,
  edited_at text,
  edited_by bigint,
  alarm_state text default 'active',
  acknowledged_at text,
  verification_quality text,
  verification_verified_at text
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id),
  request_id bigint,
  title text not null,
  message text not null,
  is_read integer not null default 0,
  created_at text not null
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  user_id bigint,
  request_id bigint,
  action text not null,
  details text,
  created_at text not null
);

create table if not exists public.public_emergencies (
  id bigint generated by default as identity primary key,
  ticket_number text unique not null,
  user_id bigint references public.users(id),
  category text not null,
  description text not null,
  address text not null,
  latitude text,
  longitude text,
  verification_image text,
  urgency text not null default 'High',
  status text not null default 'Pending',
  alarm_state text not null default 'active',
  department text,
  created_at text not null
);

-- Seed settings only. Create production admin/government credentials
-- through a controlled one-time script; do not keep demo passwords.
insert into public.app_settings(key, value, updated_at)
values ('gemini_api_key', null, now()::text)
on conflict (key) do nothing;

-- Recommended indexes
create index if not exists idx_requests_user_id on public.requests(user_id);
create index if not exists idx_requests_status on public.requests(status);
create index if not exists idx_requests_priority on public.requests(priority);
create index if not exists idx_notifications_user_id on public.notifications(user_id);
create index if not exists idx_audit_logs_request_id on public.audit_logs(request_id);
create index if not exists idx_public_emergencies_status on public.public_emergencies(status);

-- Defense-in-depth: enable RLS. The GABAY Flask server uses server-side credentials.
alter table public.users enable row level security;
alter table public.app_settings enable row level security;
alter table public.requests enable row level security;
alter table public.notifications enable row level security;
alter table public.audit_logs enable row level security;
alter table public.public_emergencies enable row level security;
